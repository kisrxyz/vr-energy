// Почему опасно: у ошибки полигона — своё (why), у ошибки движка — по виду ошибки и тексту. null — объяснения нет
function whyOf(e) {
  if (!e) return null;
  if (e.why) return e.why;
  const t = String(e.text || '');
  if (e.kind === 'supply') return WHY_OP.supply;
  if (e.kind === 'blocked') return WHY_OP.blocked;
  if (e.kind === 'proc') return /без проверки/.test(t) ? WHY_OP.check : /тележка .* при включённом выключателе/.test(t) ? WHY_OP.rackOn : null;
  if (e.kind === 'kz') return /короткозамыкатель/i.test(t) ? WHY_OP.kzOn : /предохранитель/i.test(t) ? WHY_OP.fuseGround : WHY_OP.breakerGround;
  if (e.kind === 'accident') {
    if (/ток нагрузки|включена нагрузка/.test(t)) return WHY_OP.loadBreak;
    if (/под напряжением/.test(t)) return WHY_OP.earthLive;
    if (/тележка .* вкачена/.test(t)) return WHY_OP.cartGround;
    if (/заземлённый участок/.test(t)) return WHY_OP.discGround;
  }
  return null;
}

