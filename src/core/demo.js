// Шаги показа: без готовой части (has(needs) → false) шага нет
function demoSteps(has = () => true) { return STEPS.filter(s => !s.needs || has(s.needs)); }
// Поля пилота, которые заполнены: [[подпись, значение]]
function pilotLines(p = PILOT) { return Object.keys(PILOT_LABELS).filter(k => String(p[k] || '').trim()).map(k => [PILOT_LABELS[k], String(p[k]).trim()]); }
// Сколько длится автопоказ по паузам сценария (без действий плана и подхода пешком — их время добавляет оценка ниже), мс
function autoMs(steps, planSteps = {}) {
  let ms = 0;
  for (const s of steps) for (const a of s.auto || []) {
    ms += a.wait || a.report || a.ms || 0;
    if (a.plan) ms += (planSteps[s.id] || 0) * (a.every || 1500);
    if (a.e || a.click || a.clickNew || a.ack || a.hint || a.copy || a.paste || a.mode) ms += 400;
  }
  return ms;
}

export { STEPS, PILOT, PILOT_LABELS, demoSteps, pilotLines, autoMs };
